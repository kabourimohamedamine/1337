int	ft_sqrt(int nb)
{
	int	i;
	int	j;

	i = 0;
	if (nb == 0)
		return (0);
	if (nb == 1)
		return (1);
	else
	{
		while (i <= (nb / 2))
		{
			j = i * i;
			if (j == nb)
				return (i);
			i++;
		}
	}
	return (0);
}
